import { OptimizationResult, StripLayout, OrderRow, GroupResult } from "./types";
import { calcTotalWeightKg, toMm } from "./helpers";
import { postData } from "../../../utility/utility";

type SimTotals = { totalOut: number; totalProdWeight: number };
async function getSimTotals(result: OptimizationResult, stripModes: Record<number, boolean> = {}): Promise<SimTotals> {
    const stripModesPayload = result.stripsLayout.map((_, idx) => ({ strip_idx: idx, is_full: !!stripModes[idx], manual_sheets: null, is_skipped: false }));
    try {
        const res = await postData('/zerowaste/simulate-fulfillment', { bestOpt: result, orders: result.orders, stripModes: stripModesPayload });
        if (res?.success && res?.data) return { totalOut: Number(res.data.total_output_sheets || 0), totalProdWeight: Number(res.data.total_weight_kg || 0) };
    } catch {}
    // fallback-only
    let totalOut = 0, totalProdWeight = 0;
    result.stripsLayout.forEach((s, idx) => { const qty = stripModes[idx] ? s.totalSheets : s.usableSheets; totalOut += qty; totalProdWeight += calcTotalWeightKg(s.reelSize, s.cutSize, result.reel.gsm, qty); });
    return { totalOut, totalProdWeight };
}

export async function shareOnWhatsApp(phone: string, result: OptimizationResult, reportTitle: string, stripModes: Record<number, boolean> = {}) {
    const { totalOut } = await getSimTotals(result, stripModes);
    const strips = result.stripsLayout.map((s: StripLayout, idx: number) => {
        const isFull = !!stripModes[idx];
        const qty = isFull ? s.totalSheets : s.usableSheets;
        const modeLabel = isFull ? " (FULL MODE)" : " (FIXED)";
        return `  • ${s.client}: ${s.reelSize.toFixed(1)}mm × ${s.cutSize.toFixed(1)}mm = *${qty.toLocaleString()} sheets*${modeLabel}`;
    }).join("\n");

    const msg = encodeURIComponent(
        `📄 *${reportTitle}*\n` +
        `📅 Date: ${new Date().toLocaleDateString("en-IN")}\n\n` +
        `🎞️ Roll No: *${result.reel.reelNo}*\n` +
        `📐 Reel Size: *${result.reel.width} ${result.reel.sizeUnit}*\n` +
        `⚖️ GSM: *${result.reel.gsm}*  |  Quality: *${result.reel.quality}*\n\n` +
        `📦 *Selected Layout & Quantities:*\n${strips}\n\n` +
        `📊 Total Output: *${totalOut.toLocaleString()} Sheets*\n` +
        `📊 Trim Loss: ${result.trimWasteMm.toFixed(0)} mm (${result.trimWastePercent.toFixed(1)}%)\n\n` +
        (result.approvalNeeded
            ? `🙏 *Approval Required*: Please approve this configuration.\n\n`
            : `✅ Production can begin — no approval needed!\n\n`) +
        `_Generated by JAIN TRADE LINKS Smart System_`
    );

    const url = phone
        ? `https://wa.me/91${phone.replace(/\D/g, "")}?text=${msg}`
        : `https://wa.me/?text=${msg}`;
    window.open(url, "_blank");
}

export async function generatePDFData(result: OptimizationResult, stripModes: Record<number, boolean> = {}) {
    const doc = new jsPDF();
    const pageWidth = doc.internal.pageSize.getWidth();
    const combined = result.trimWastePercent;

    if (result.isZeroWaste) {
        doc.setFillColor(22, 163, 74);
    } else {
        doc.setFillColor(37, 99, 235);
    }
    doc.rect(0, 0, pageWidth, 42, "F");
    doc.setTextColor(255, 255, 255);
    doc.setFontSize(20);
    doc.setFont("helvetica", "bold");
    doc.text("JAIN TRADE LINKS", 14, 18);
    doc.setFontSize(9);
    doc.text(
        result.isZeroWaste ? "ZERO WASTE PRODUCTION REPORT" : "WASTE ANALYSIS — CUSTOMER APPROVAL REQUIRED",
        14, 28
    );
    doc.text(new Date().toLocaleDateString("en-IN"), pageWidth - 50, 18);
    doc.text(new Date().toLocaleTimeString("en-IN", { hour: "2-digit", minute: "2-digit" }), pageWidth - 50, 26);

    if (result.isZeroWaste) {
        doc.setFillColor(22, 163, 74);
    } else if (combined <= 5) {
        doc.setFillColor(234, 179, 8);
    } else {
        doc.setFillColor(239, 68, 68);
    }
    doc.roundedRect(pageWidth - 52, 30, 40, 9, 2, 2, "F");
    doc.setTextColor(255, 255, 255);
    doc.setFontSize(7);
    doc.text(result.isZeroWaste ? "0% WASTE ✓" : `${combined.toFixed(1)}% TRIM LOSS`, pageWidth - 32, 36, { align: "center" });

    doc.setTextColor(31, 41, 55);
    doc.setFontSize(11);
    doc.setFont("helvetica", "bold");
    doc.text("Roll / Reel Information", 14, 55);
    autoTable(doc, {
        startY: 58,
        head: [["Field", "Details"]],
        body: [
            ["Roll Number", result.reel.reelNo],
            ["Reel Size", `${result.reel.width} ${result.reel.sizeUnit}`],
            ["GSM", `${result.reel.gsm} GSM`],
            ["Quality", result.reel.quality],
            ["Available Balance", `${result.reel.currentBalanceKg.toFixed(2)} Kg`],
        ],
        theme: "striped",
        headStyles: { fillColor: [243, 244, 246], textColor: [75, 85, 99], fontStyle: "bold" },
    });

    const finalY1 = (doc as any).lastAutoTable.finalY + 10;
    doc.setFontSize(12);
    doc.setFont("helvetica", "bold");
    doc.text("Order Requirements", 14, finalY1);
    autoTable(doc, {
        startY: finalY1 + 3,
        head: [["Party/Client", "Reel Size", "Cutting Size", "Qty Ordered"]],
        body: result.orders.map((o: OrderRow) => [
            o.client || "—",
            `${o.reelSize} ${o.reelSizeUnit}`,
            `${o.cutSize} ${o.cutSizeUnit}`,
            `${Number(o.qty).toLocaleString()} Sheets`,
        ]),
        theme: "grid",
        headStyles: { fillColor: [37, 99, 235], textColor: [255, 255, 255] },
    });

    const finalY2 = (doc as any).lastAutoTable.finalY + 10;
    doc.setFontSize(12);
    doc.text("Production Plan (Selected Layout)", 14, finalY2);
    const { totalOut, totalProdWeight } = await getSimTotals(result, stripModes);

    autoTable(doc, {
        startY: finalY2 + 3,
        head: [["Party", "Width (mm)", "Height (mm)", "Strips", "Sheets Produced", "Mode", "Status"]],
        body: result.stripsLayout.map((s: StripLayout, idx: number) => {
            const isFull = !!stripModes[idx];
            const qty = isFull ? s.totalSheets : s.usableSheets;
            return [
                s.client,
                s.reelSize.toFixed(1),
                s.cutSize.toFixed(1),
                s.count,
                qty.toLocaleString(),
                isFull ? "FULL" : "FIXED",
                isFull ? "Utilizing Extra" : "Exact Order"
            ];
        }),
        theme: "grid",
        headStyles: { fillColor: [79, 70, 229], textColor: [255, 255, 255] },
        foot: [[
            { content: "Total Production Weight", colSpan: 4, styles: { fontStyle: "bold", halign: "right" } },
            { content: `${totalProdWeight.toFixed(2)} Kg`, colSpan: 3, styles: { fontStyle: "bold" } }
        ]],
        footStyles: { fillColor: [248, 250, 252], textColor: [31, 41, 55] }
    });

    const finalY3 = (doc as any).lastAutoTable.finalY + 12;
    doc.setFillColor(249, 250, 251);
    doc.rect(14, finalY3, pageWidth - 28, 35, "F");
    doc.setTextColor(75, 85, 99);
    doc.setFontSize(10);
    doc.text("WASTE SUMMARY ANALYSIS", 18, finalY3 + 8);
    doc.setFontSize(9);
    doc.text(`Total Ordered Sheets: ${result.totalOrderedSheets.toLocaleString()}`, 18, finalY3 + 16);
    doc.text(`Total Selected Output: ${totalOut.toLocaleString()} sheets`, 18, finalY3 + 22);

    if (result.isZeroWaste) {
        doc.setTextColor(22, 163, 74);
    } else {
        doc.setTextColor(220, 38, 38);
    }
    doc.setFont("helvetica", "bold");
    doc.text(`Trim Loss: ${result.trimWasteMm.toFixed(0)} mm (${result.trimWastePercent.toFixed(1)}%)`, 18, finalY3 + 28);
    doc.text(`Total Reel Width: ${result.reelWidth.toFixed(1)} mm`, 18, finalY3 + 34);

    const finalY4 = finalY3 + 45;
    doc.setTextColor(31, 41, 55);
    doc.setFont("helvetica", "bold");
    doc.text(`Note: Production configuration respects strip-level 'Fixed' and 'Full' selections.`, 14, finalY4);

    doc.setTextColor(107, 114, 128);
    doc.setFont("helvetica", "normal");
    doc.text("Generated by JAIN TRADE LINKS SMART SYSTEM", pageWidth / 2, 287, { align: "center" });

    return doc;
}

export async function generatePDF(result: OptimizationResult, stripModes: Record<number, boolean> = {}) {
    const doc = await generatePDFData(result, stripModes);
    doc.save(`ZeroWaste_${result.reel.reelNo}_Plan.pdf`);
    toast.success("PDF Report downloaded!");
}

export async function shareReportPDF(result: OptimizationResult, stripModes: Record<number, boolean> = {}) {
    const doc = await generatePDFData(result, stripModes);
    const fileName = `Report_Roll_${result.reel.reelNo}.pdf`;
    const pdfBlob = doc.output('blob');
    const file = new File([pdfBlob], fileName, { type: "application/pdf" });

    if (navigator.share && navigator.canShare && navigator.canShare({ files: [file] })) {
        try {
            await navigator.share({
                files: [file],
                title: "Paper Cutting Analysis",
                text: `Production Plan for Roll #${result.reel.reelNo}`,
            });
        } catch (err) {
            console.error("Share failed", err);
            doc.save(fileName);
        }
    } else {
        doc.save(fileName);
        toast.info("Direct sharing is not supported on desktop. PDF downloaded.");
    }
}

// 📱 SINGLE CLIENT WHATSAPP SUMMARY — Format requested by USER
export async function shareClientSummaryOnWhatsApp(
    phone: string,
    clientName: string,
    orders: OrderRow[],
    groupResults: GroupResult[],
    selectedRollIndices: Record<string, number>
) {
    // Helper: backend-primary weight via total-weight endpoint, fallback local
    const getWeightKg = async (wMm:number, hMm:number, gsm:number, sheets:number) => {
        try {
            const res = await postData('/calculations/total-weight', { width_mm: wMm, height_mm: hMm, gsm, sheets, rounding_mode: 'raw' });
            if (res?.success && res?.data?.total_weight_kg !== undefined) return Number(res.data.total_weight_kg);
        } catch {}
        return calcTotalWeightKg(wMm, hMm, gsm, sheets);
    };

    // Backend-primary logical summary generation, local fallback
    try {
        const res = await postData('/zerowaste/share-summary', { phone, clientName, orders, groupResults, selectedRollIndices });
        if (res?.success && res?.data?.message) {
            const url = phone
                ? `https://wa.me/91${phone.replace(/\D/g, "")}?text=${encodeURIComponent(res.data.message)}`
                : `https://wa.me/?text=${encodeURIComponent(res.data.message)}`;
            window.open(url, "_blank");
            toast.success(`WhatsApp summary for ${clientName} opened!`);
            return;
        }
    } catch (e) {
        console.warn('share-summary backend failed, using local fallback', e);
    }

    let msg = `*For customer- ${clientName}*\n\n`;

    msg += `*Required order-*\n`;
    for (let idx = 0; idx < orders.length; idx++) {
        const o = orders[idx];
        const wMm = toMm(Number(o.reelSize) || 0, o.reelSizeUnit);
        const hMm = toMm(Number(o.cutSize) || 0, o.cutSizeUnit);
        const gsm = Number(o.gsm) || 0;
        const qty = Number(o.qty) || 0;
        const weight = await getWeightKg(wMm, hMm, gsm, qty);

        msg += `${idx + 1}) ${o.reelSize}${o.reelSizeUnit} x ${o.cutSize}${o.cutSizeUnit}- ${gsm} Gsm\n`;
        msg += `${qty.toLocaleString()} sheets or ${weight.toFixed(2)} kg\n\n`;
    }

    msg += `*Available order-*\n`;
    for (let idx = 0; idx < orders.length; idx++) {
        const o = orders[idx];
        let fullTotalFirstToNMinus1 = 0;
        let fullTotalLastGroup = 0;
        let usableLastGroup = 0;
        let firstStripTotalLastGroup = 0;       // sheets from P1 only (skip scenario)
        let hasShortfallStripLastGroup = false;  // true when P2+ exists (shortfall was covered)

        const validGroups = groupResults.filter(g => {
            const orderInGroup = g.group.orders.find(ord => ord.id === o.id);
            return orderInGroup && g.rollOptions.length > 0;
        });

        validGroups.forEach((g, gIdx) => {
            const selectedIdx = selectedRollIndices[g.group.key] || 0;
            const bestOpt = g.rollOptions[selectedIdx] || g.rollOptions[0];
            const orderStrips = bestOpt.stripsLayout.filter(s => s.orderId === o.id);

            const fullTotal = orderStrips.reduce((sum, s) => sum + s.totalSheets, 0);
            const usableTotal = orderStrips.reduce((sum, s) => sum + s.usableSheets, 0);

            if (gIdx < validGroups.length - 1) {
                fullTotalFirstToNMinus1 += fullTotal;
            } else {
                fullTotalLastGroup = fullTotal;
                usableLastGroup = usableTotal;
                // For shortfall scenario: P1's totalSheets = what you get if you skip P2
                firstStripTotalLastGroup = orderStrips.length > 0 ? orderStrips[0].totalSheets : 0;
                hasShortfallStripLastGroup = orderStrips.length > 1;
            }
        });

        const req = Number(o.qty) || 0;
        const wMmO = toMm(Number(o.reelSize) || 0, o.reelSizeUnit);
        const hMmO = toMm(Number(o.cutSize) || 0, o.cutSizeUnit);
        const gsmO = Number(o.gsm) || 0;

        let Option1Qty = 0;
        let Option2Qty = 0;
        let labelSuffix1 = "";
        let labelSuffix2 = "";

        if (validGroups.length > 1) {
            // Multiple rolls — Option A: all rolls full, Option B: skip last roll
            Option1Qty = fullTotalFirstToNMinus1 + fullTotalLastGroup;
            Option2Qty = fullTotalFirstToNMinus1;
            labelSuffix1 = "(Full — All Rolls Used)";
            labelSuffix2 = "(Save Last Roll)";
        } else if (validGroups.length === 1) {
            if (hasShortfallStripLastGroup) {
                // Shortfall scenario: P2 exists but customer can skip it
                // Option A = Full production (both strips run fully)
                // Option B = Skip P2 (take only P1's output)
                Option1Qty = fullTotalLastGroup;         // e.g. 11,070 (P1+P2 fully)
                Option2Qty = firstStripTotalLastGroup;  // e.g.  5,535 (P1 only, skip P2)
                labelSuffix1 = "(Full Production)";
                labelSuffix2 = "(Customer Accepted Reduced — Skip Strip)";
            } else {
                // Normal single-roll: Fixed vs Full toggle
                Option1Qty = usableLastGroup;
                Option2Qty = fullTotalLastGroup;
                labelSuffix1 = "(Fixed Mode)";
                labelSuffix2 = "(Full Mode)";
            }
        }

        const opt1Diff = Option1Qty - req;
        const opt1Weight = await getWeightKg(wMmO, hMmO, gsmO, Option1Qty);

        const opt2Diff = Option2Qty - req;
        const opt2Weight = await getWeightKg(wMmO, hMmO, gsmO, Option2Qty);

        const formatOpt = (qty: number, diff: number) => {
            if (qty === 0 && req > 0) return `0`;
            if (diff === 0) return `${req} (Exact)`;
            return diff < 0
                ? `${req} - ${Math.abs(diff)} = ${qty.toLocaleString()}`
                : `${req} + ${diff} = ${qty.toLocaleString()}`;
        };

        const opt1Str = formatOpt(Option1Qty, opt1Diff);
        const opt2Str = formatOpt(Option2Qty, opt2Diff);

        msg += `${idx + 1}) ${o.reelSize}${o.reelSizeUnit} x ${o.cutSize}${o.cutSizeUnit}- ${o.gsm} Gsm\n`;
        msg += `Available quantity-\n`;
        
        if (validGroups.length === 0) {
             msg += `No rolls assigned yet.\n\n`;
        } else {
             msg += `Option 1 ${labelSuffix1}: ${opt1Str} sheets (${opt1Weight.toFixed(2)} kg)\n`;
             msg += `Option 2 ${labelSuffix2}: ${opt2Str} sheets (${opt2Weight.toFixed(2)} kg)\n\n`;
        }
    }

    msg += `_Generated by JAIN TRADE LINKS Smart System_`;

    const url = phone
        ? `https://wa.me/91${phone.replace(/\D/g, "")}?text=${encodeURIComponent(msg)}`
        : `https://wa.me/?text=${encodeURIComponent(msg)}`;

    window.open(url, "_blank");
    toast.success(`WhatsApp summary for ${clientName} opened!`);
}
